"""PostgreSQL storage adapter for the single-store website."""

from __future__ import annotations

import hashlib
import io
import os
import uuid
from datetime import date
from pathlib import Path

import pandas as pd
from sqlalchemy import create_engine, text
from sqlalchemy.engine import URL


ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
STORE_ID = "__SINGLE_STORE__"


def _engine():
    required = ("DB_HOST", "DB_NAME", "DB_USER", "DB_PASSWORD")
    missing = [name for name in required if not os.environ.get(name)]
    if missing:
        raise RuntimeError("Missing database settings: " + ", ".join(missing))
    return create_engine(
        URL.create(
            "postgresql+psycopg",
            username=os.environ["DB_USER"],
            password=os.environ["DB_PASSWORD"],
            host=os.environ["DB_HOST"],
            port=int(os.environ.get("DB_PORT", "5432")),
            database=os.environ["DB_NAME"],
            query={"sslmode": os.environ.get("DB_SSLMODE", "require")},
        ),
        pool_pre_ping=True,
    )


ENGINE = _engine()


def connect():
    """Return a SQLAlchemy connection; prefer ENGINE.begin() for writes."""
    return ENGINE.connect()


def init_db() -> None:
    statements = (
        """CREATE TABLE IF NOT EXISTS branches (
            branch_id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            location TEXT NOT NULL DEFAULT ''
        )""",
        """CREATE TABLE IF NOT EXISTS products (
            sku TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            category TEXT NOT NULL DEFAULT '',
            storage_location TEXT NOT NULL DEFAULT '',
            lead_time_days INTEGER NOT NULL DEFAULT 7 CHECK (lead_time_days >= 0),
            safety_stock INTEGER NOT NULL DEFAULT 0 CHECK (safety_stock >= 0)
        )""",
        """CREATE TABLE IF NOT EXISTS inventory (
            branch_id TEXT NOT NULL REFERENCES branches(branch_id) ON DELETE RESTRICT,
            sku TEXT NOT NULL REFERENCES products(sku) ON DELETE RESTRICT,
            quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
            PRIMARY KEY (branch_id, sku)
        )""",
        """CREATE TABLE IF NOT EXISTS sales (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sale_date DATE NOT NULL,
            branch_id TEXT NOT NULL REFERENCES branches(branch_id) ON DELETE RESTRICT,
            sku TEXT NOT NULL REFERENCES products(sku) ON DELETE RESTRICT,
            quantity INTEGER NOT NULL CHECK (quantity > 0),
            source TEXT NOT NULL,
            source_key TEXT NOT NULL UNIQUE
        )""",
        "CREATE INDEX IF NOT EXISTS sales_series_date ON sales(branch_id, sku, sale_date)",
        """CREATE TABLE IF NOT EXISTS imports (
            file_hash TEXT PRIMARY KEY,
            file_name TEXT NOT NULL,
            imported_rows INTEGER NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS alerts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            branch_id TEXT NOT NULL,
            sku TEXT NOT NULL,
            message TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS alert_state (
            sku TEXT PRIMARY KEY REFERENCES products(sku) ON DELETE CASCADE,
            active BOOLEAN NOT NULL DEFAULT FALSE
        )""",
        """CREATE TABLE IF NOT EXISTS import_jobs (
            file_hash TEXT PRIMARY KEY,
            file_name TEXT NOT NULL,
            s3_key TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'queued',
            imported_rows INTEGER NOT NULL DEFAULT 0,
            error TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS sns_message_id TEXT",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS is_automatic BOOLEAN NOT NULL DEFAULT FALSE",
    )
    with ENGINE.begin() as connection:
        for statement in statements:
            connection.execute(text(statement))
        connection.execute(
            text("""INSERT INTO branches(branch_id, name, location)
                VALUES (:branch_id, 'My store', '') ON CONFLICT (branch_id) DO NOTHING"""),
            {"branch_id": STORE_ID},
        )


def table(name: str) -> pd.DataFrame:
    allowed = {
        "products": "SELECT * FROM products ORDER BY sku",
        "inventory": """SELECT i.sku, p.name AS product_name, i.quantity,
            p.safety_stock, p.lead_time_days FROM inventory i
            JOIN products p USING(sku) WHERE i.branch_id=:branch_id ORDER BY i.sku""",
        "sales": "SELECT sale_date, sku, quantity, source FROM sales ORDER BY sale_date DESC, id DESC",
        "imports": "SELECT * FROM imports ORDER BY created_at DESC",
        "alerts": """SELECT id, sku, message, created_at,
            CASE WHEN sns_message_id IS NOT NULL THEN 'sent'
                 WHEN is_automatic THEN 'pending' ELSE 'manual' END AS email_status
            FROM alerts ORDER BY id DESC""",
        "import_jobs": "SELECT file_name, status, imported_rows, error, created_at, updated_at FROM import_jobs ORDER BY created_at DESC",
    }
    if name not in allowed:
        raise ValueError("Unknown table")
    with ENGINE.connect() as connection:
        return pd.read_sql_query(text(allowed[name]), connection,
                                 params={"branch_id": STORE_ID} if name == "inventory" else None)


def save_product(sku: str, name: str, category: str, storage_location: str,
                 lead_time_days: int, safety_stock: int) -> None:
    sku, name = sku.strip(), name.strip()
    if not sku or not name:
        raise ValueError("SKU and product name are required")
    with ENGINE.begin() as connection:
        connection.execute(text("""INSERT INTO products
            (sku, name, category, storage_location, lead_time_days, safety_stock)
            VALUES (:sku, :name, :category, :storage_location, :lead_time_days, :safety_stock)
            ON CONFLICT (sku) DO UPDATE SET name=EXCLUDED.name,
            category=EXCLUDED.category, storage_location=EXCLUDED.storage_location,
            lead_time_days=EXCLUDED.lead_time_days, safety_stock=EXCLUDED.safety_stock"""),
            {"sku": sku, "name": name, "category": category.strip(),
             "storage_location": storage_location.strip(),
             "lead_time_days": int(lead_time_days), "safety_stock": int(safety_stock)})


def delete_product(sku: str) -> None:
    with ENGINE.begin() as connection:
        connection.execute(text("DELETE FROM products WHERE sku=:sku"), {"sku": sku})


def set_inventory(sku: str, quantity: int) -> None:
    if quantity < 0:
        raise ValueError("Stock cannot be negative")
    with ENGINE.begin() as connection:
        connection.execute(text("""INSERT INTO inventory(branch_id, sku, quantity)
            VALUES (:branch_id, :sku, :quantity)
            ON CONFLICT (branch_id, sku) DO UPDATE SET quantity=EXCLUDED.quantity"""),
            {"branch_id": STORE_ID, "sku": sku, "quantity": int(quantity)})


def delete_inventory(sku: str) -> None:
    with ENGINE.begin() as connection:
        connection.execute(text("""DELETE FROM inventory
            WHERE branch_id=:branch_id AND sku=:sku"""),
            {"branch_id": STORE_ID, "sku": sku})
        connection.execute(text("UPDATE alert_state SET active=FALSE WHERE sku=:sku"),
                           {"sku": sku})


def add_sale(sale_date: date, sku: str, quantity: int,
             reduce_stock: bool = False) -> None:
    if quantity <= 0:
        raise ValueError("Quantity sold must be positive")
    with ENGINE.begin() as connection:
        if reduce_stock:
            updated = connection.execute(text("""UPDATE inventory
                SET quantity=quantity-:quantity
                WHERE branch_id=:branch_id AND sku=:sku AND quantity>=:quantity"""),
                {"quantity": int(quantity), "branch_id": STORE_ID, "sku": sku}).rowcount
            if updated != 1:
                raise ValueError("Not enough stock recorded for this product")
        connection.execute(text("""INSERT INTO sales
            (sale_date, branch_id, sku, quantity, source, source_key)
            VALUES (:sale_date, :branch_id, :sku, :quantity, 'manual', :source_key)"""),
            {"sale_date": sale_date, "branch_id": STORE_ID, "sku": sku,
             "quantity": int(quantity), "source_key": uuid.uuid4().hex})


def import_sales_csv(file_bytes: bytes, file_name: str) -> int:
    """Validate before a transactional import; a previously imported file adds zero rows."""
    file_hash = hashlib.sha256(file_bytes).hexdigest()
    try:
        frame = pd.read_csv(io.BytesIO(file_bytes), dtype=str)
    except Exception as exc:
        raise ValueError(f"Cannot read CSV: {exc}") from exc
    frame.columns = frame.columns.str.strip()
    required = {"sale_date", "sku", "quantity_sold"}
    if not required.issubset(frame.columns):
        raise ValueError(f"Missing CSV columns: {', '.join(sorted(required - set(frame.columns)))}")
    if frame.empty:
        raise ValueError("CSV is empty")
    if "branch_id" in frame.columns:
        raise ValueError("Remove branch_id from the CSV. This app now has one store.")
    parsed_dates = pd.to_datetime(frame["sale_date"], format="%Y-%m-%d", errors="coerce")
    qty = pd.to_numeric(frame["quantity_sold"], errors="coerce")
    if parsed_dates.isna().any():
        raise ValueError("sale_date must use YYYY-MM-DD in every row")
    if qty.isna().any() or (qty <= 0).any() or (qty % 1 != 0).any():
        raise ValueError("quantity_sold must be a positive whole number")
    skus = frame["sku"].fillna("").str.strip()
    if (skus == "").any():
        raise ValueError("sku cannot be blank")

    with ENGINE.begin() as connection:
        known_skus = set(connection.execute(text("SELECT sku FROM products")).scalars())
        missing_skus = set(skus) - known_skus
        if missing_skus:
            raise ValueError(f"Create products first. Missing SKUs: {sorted(missing_skus)}")
        claimed = connection.execute(text("""INSERT INTO imports
            (file_hash, file_name, imported_rows)
            VALUES (:file_hash, :file_name, :imported_rows)
            ON CONFLICT (file_hash) DO NOTHING RETURNING file_hash"""),
            {"file_hash": file_hash, "file_name": file_name,
             "imported_rows": len(frame)}).scalar_one_or_none()
        if claimed is None:
            return 0
        rows = [
            {"sale_date": parsed_dates.iloc[i].date(), "branch_id": STORE_ID,
             "sku": skus.iloc[i], "quantity": int(qty.iloc[i]),
             "source_key": f"{file_hash}:{i}"}
            for i in range(len(frame))
        ]
        connection.execute(text("""INSERT INTO sales
            (sale_date, branch_id, sku, quantity, source, source_key)
            VALUES (:sale_date, :branch_id, :sku, :quantity, 'csv', :source_key)"""), rows)

    upload_dir = DATA_DIR / "uploads"
    upload_dir.mkdir(parents=True, exist_ok=True)
    (upload_dir / f"{file_hash}.csv").write_bytes(file_bytes)
    return len(frame)


def weekly_sales(sku: str) -> pd.Series:
    with ENGINE.connect() as connection:
        frame = pd.read_sql_query(text("""SELECT sale_date, quantity FROM sales
            WHERE branch_id=:branch_id AND sku=:sku ORDER BY sale_date"""),
            connection, params={"branch_id": STORE_ID, "sku": sku})
    if frame.empty:
        return pd.Series(dtype=float)
    frame["sale_date"] = pd.to_datetime(frame["sale_date"])
    weekly = frame.groupby(pd.Grouper(key="sale_date", freq="W-SUN"))["quantity"].sum()
    return weekly.asfreq("W-SUN", fill_value=0).astype(float)


def log_alert(sku: str, message: str) -> None:
    with ENGINE.begin() as connection:
        connection.execute(text("""INSERT INTO alerts(branch_id, sku, message)
            VALUES (:branch_id, :sku, :message)"""),
            {"branch_id": STORE_ID, "sku": sku, "message": message})


def queue_import(file_hash: str, file_name: str, s3_key: str) -> bool:
    """Return false for a file already imported or currently queued."""
    with ENGINE.begin() as connection:
        if connection.execute(text("SELECT 1 FROM imports WHERE file_hash=:hash"),
                              {"hash": file_hash}).first():
            return False
        row = connection.execute(text("SELECT status FROM import_jobs WHERE file_hash=:hash"),
                                 {"hash": file_hash}).first()
        if row and row[0] in ("queued", "processing", "completed"):
            return False
        connection.execute(text("""INSERT INTO import_jobs(file_hash,file_name,s3_key,status,error,updated_at)
            VALUES (:hash,:name,:key,'queued','',CURRENT_TIMESTAMP)
            ON CONFLICT(file_hash) DO UPDATE SET status='queued',error='',
                updated_at=CURRENT_TIMESTAMP"""),
            {"hash": file_hash, "name": file_name, "key": s3_key})
        return True


def fail_import(file_hash: str, reason: str) -> None:
    with ENGINE.begin() as connection:
        connection.execute(text("""UPDATE import_jobs SET status='failed', error=:error,
            updated_at=CURRENT_TIMESTAMP WHERE file_hash=:hash"""),
            {"error": reason[:1000], "hash": file_hash})


def record_reorder_transition(sku: str, message: str, below_point: bool) -> bool:
    """Create one alert per crossing below the threshold, atomically."""
    with ENGINE.begin() as connection:
        connection.execute(text("""INSERT INTO alert_state(sku,active) VALUES (:sku,FALSE)
            ON CONFLICT(sku) DO NOTHING"""), {"sku": sku})
        if not below_point:
            connection.execute(text("UPDATE alert_state SET active=FALSE WHERE sku=:sku"),
                               {"sku": sku})
            return False
        changed = connection.execute(text("""UPDATE alert_state SET active=TRUE
            WHERE sku=:sku AND active=FALSE RETURNING sku"""), {"sku": sku}).first()
        if not changed:
            return False
        connection.execute(text("""INSERT INTO alerts(branch_id,sku,message,is_automatic)
            VALUES (:branch,:sku,:message,TRUE)"""),
            {"branch": STORE_ID, "sku": sku, "message": message})
        return True


def pending_alerts() -> list[dict]:
    with ENGINE.connect() as connection:
        rows = connection.execute(text("""SELECT id,sku,message FROM alerts
            WHERE sns_message_id IS NULL AND is_automatic=TRUE ORDER BY id LIMIT 25""")).mappings().all()
    return [dict(row) for row in rows]


def mark_alert_sent(alert_id: int, message_id: str) -> None:
    with ENGINE.begin() as connection:
        connection.execute(text("""UPDATE alerts SET sns_message_id=:message_id
            WHERE id=:id AND sns_message_id IS NULL"""),
            {"id": alert_id, "message_id": message_id})
